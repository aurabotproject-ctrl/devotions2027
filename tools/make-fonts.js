/* Builds css/fonts.css with base64-embedded woff2 fonts (so the app works offline over file://).
   Usage:  npm i @fontsource/bangers @fontsource/baloo-2 @fontsource/atkinson-hyperlegible @fontsource/caveat
           node tools/make-fonts.js [path/to/node_modules] */
const fs = require("fs"), path = require("path");
const nm = process.argv[2] || path.join(process.cwd(), "node_modules");
const LATIN = "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD";
const EXT = "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF";
const list = [
  ["Bangers", "bangers", 400, "normal", ["latin"]],
  ["Baloo 2", "baloo-2", 600, "normal", ["latin", "latin-ext"]],
  ["Baloo 2", "baloo-2", 800, "normal", ["latin", "latin-ext"]],
  ["Atkinson Hyperlegible", "atkinson-hyperlegible", 400, "normal", ["latin", "latin-ext"]],
  ["Atkinson Hyperlegible", "atkinson-hyperlegible", 700, "normal", ["latin", "latin-ext"]],
  ["Atkinson Hyperlegible", "atkinson-hyperlegible", 400, "italic", ["latin", "latin-ext"]],
  ["Caveat", "caveat", 700, "normal", ["latin", "latin-ext"]]
];
let css = "/* Generated by tools/make-fonts.js — fonts are SIL Open Font License (OFL) */\n";
list.forEach(([fam, pkg, w, st, subsets]) => subsets.forEach(sub => {
  const f = path.join(nm, "@fontsource", pkg, "files", `${pkg}-${sub}-${w}-${st}.woff2`);
  if (!fs.existsSync(f)) { console.warn("missing", f); return; }
  const b64 = fs.readFileSync(f).toString("base64");
  css += `@font-face{font-family:"${fam}";font-style:${st};font-weight:${w};font-display:swap;src:url(data:font/woff2;base64,${b64}) format("woff2");unicode-range:${sub === "latin" ? LATIN : EXT};}\n`;
}));
fs.writeFileSync(path.join(__dirname, "..", "css", "fonts.css"), css);
console.log("css/fonts.css written,", Math.round(css.length / 1024), "KB");
